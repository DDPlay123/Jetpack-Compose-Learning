package mai.project.compose.core

/**
 * # 關於 `@Immutable` 與 `@Stable`：
 *
 * 在 Jetpack Compose 中，這兩個註解主要幫助 Compose 更精準地判斷
 * 「物件內容是否改變」，以便在重組 (Recomposition) 過程中進行最佳化：
 *
 * 1. `@Immutable`
 *    - 用於標記 **完全不可變** (Immutable) 的類別或資料結構。
 *    - 條件：所有屬性必須是不可變型態 (如 String、Int、其他 `@Immutable` 類等等)，
 *      沒有任何可變集合 (如 MutableList) 或可被改變的欄位 (var)。
 *    - 好處：如果 Compose 發現物件引用 (reference) 沒變，就能保證內容也沒變，
 *      可以**跳過**不必要的重組。
 *    - 注意：若呼叫 `copy()` 或以任何方式產生 **新的物件引用**，視為整個物件「改變」，
 *      依賴此物件的 Composable 會重組。
 *
 * 2. `@Stable`
 *    - 用於標記在行為上「可被追蹤、可預測」的類別，容許內部有可變欄位 (var)，
 *      但必須保證此類別的變化對 Compose 而言是可分析的，且不會造成未預期的同步問題。
 *    - 好處：標註為 `@Stable` 後，Compose 可能更精準地判斷其中的哪個屬性改變，
 *      在理想情況下，只重組真正改變的部分或依賴該屬性的子 Composable。
 *    - 注意：`@Stable` 並不自動保證「只更新某個欄位就不會影響其他欄位的 Composable」。
 *      若父層 Composable 同時把同一個 stable 物件引用傳給多個子組件，
 *      只要它們依賴的屬性有改變，仍然都會重組。實務上仍需合理拆分資料與引用，
 *      並確保此類物件真正符合「穩定 (Stable)」的行為。
 *
 * # 常見誤解：
 * 1. 「@Immutable 會導致整個大範圍重組，@Stable 就只會局部重組」──不一定如此。
 *    - 任何新物件參考 (包括 Immutable) 都會觸發重組，但重組範圍取決於此物件被誰持有、
 *      依賴哪些參數，以及是否進一步切分成多個子物件。
 * 2. 「使用 copy() 改變部分欄位就能避免重組其他欄位」──仍可能重組依賴同一物件的所有 Composable。
 *    - 若要更細顆粒度的跳過重組，需考慮將資料切分成多個 Immutable/Stable 物件，
 *      並在父層按需傳遞各自的引用。
 *
 * # 建議：
 * - 在專案中盡量讓資料結構保持不可變 (Immutable) 以利維護與測試，
 *   並搭配細顆粒度的資料切分，減少「任何小改都要整個物件換引用」的情況。
 * - 若因需求需使用可變欄位，確保類行為對 Compose 而言是可追蹤、可預測，再標註 `@Stable`。
 * - 標註這些註解後，Compose 才能做更進一步的效能優化、局部重組；否則會用「保守」方式處理。
 */
